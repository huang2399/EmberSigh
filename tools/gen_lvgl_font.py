# -*- coding: utf-8 -*-
"""
离线生成 LVGL v9 位图字体 —— 无需 lv_font_conv / npm / 网络

用法: python gen_lvgl_font.py

输出:
  main/fonts/embersigh_fonts.h
  main/fonts/embersigh_fonts.c   (包含 embersigh_font_cjk16 / cjk14 两个字体)

格式要点（对照 lv_font_fmt_txt.c 源码确认）:
  - bpp=4, bitmap_format=PLAIN(0)
  - bitmap_index 是【字节】偏移，因此每个字形按字节对齐
  - 4bpp 连续打包，高 nibble 在前，行之间不重新对齐
  - glyph_dsc[0] 保留不用，glyph_id 从 1 开始
  - 稀疏 cmap(SPARSE_TINY): 码点 = range_start + unicode_list[i]，列表必须升序
"""
import io, os
from PIL import Image, ImageDraw, ImageFont

OUT_DIR  = r'C:\Users\27568\Desktop\DreamState\EmberSigh\main\fonts'
FONT_PATH = r'C:\Windows\Fonts\Noto Sans SC (TrueType).otf'

# 需要渲染的汉字（UI 里用到的全部文案）
CHINESE = "听眠正在恢复环境静谧平稳稍响已暂停香氛音量渐入待机中"

# 生成两个字号
SIZES = [
    ('embersigh_font_cjk16', 16),
    ('embersigh_font_cjk14', 14),
]

os.makedirs(OUT_DIR, exist_ok=True)


def render_glyph(font, ch, ascent):
    """返回 (mask_image, bbox) —— bbox 相对行顶部原点"""
    bbox = font.getbbox(ch)          # (left, top, right, bottom)
    adv = font.getlength(ch)
    if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
        return None, (0, 0, 0, 0), adv
    img = Image.new('L', (bbox[2] - bbox[0], bbox[3] - bbox[1]), 0)
    d = ImageDraw.Draw(img)
    # 以 (0,0) 为行顶部原点绘制，再用 bbox 偏移裁切
    d.text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
    return img, bbox, adv


def pack_nibbles(img):
    """4bpp 连续打包，高 nibble 在前，字节对齐"""
    w, h = img.size
    px = img.load()
    out = bytearray()
    cur = 0
    half = False
    for y in range(h):
        for x in range(w):
            v = (px[x, y] + 8) // 17       # 0..255 -> 0..15
            if v > 15:
                v = 15
            if not half:
                cur = v << 4
                half = True
            else:
                cur |= v
                out.append(cur)
                half = False
    if half:
        out.append(cur)                     # 补半个字节，保证字节对齐
    return bytes(out)


def build_font(name, size):
    font = ImageFont.truetype(FONT_PATH, size)
    ascent, descent = font.getmetrics()
    line_height = ascent + descent

    chars = [chr(c) for c in range(0x20, 0x7F)] + list(CHINESE)

    glyphs = []          # (cp, box_w, box_h, ofs_x, ofs_y, adv_w, bitmap_bytes, bitmap_index)
    bitmap = bytearray()
    dummy = dict(box_w=0, box_h=0, ofs_x=0, ofs_y=0, adv_w=0,
                 bitmap_index=0, bitmap=b'')

    entries = []
    for ch in chars:
        cp = ord(ch)
        img, bbox, adv = render_glyph(font, ch, ascent)
        if img is None:
            entries.append((cp, dict(box_w=0, box_h=0, ofs_x=0, ofs_y=0,
                                     adv_w=int(round(adv * 16)), bitmap_index=len(bitmap),
                                     bitmap=b'')))
            continue
        bw, bh = img.size
        ofs_x = bbox[0]
        ofs_y = bbox[1]                     # 相对行顶部
        adv_w = int(round(adv * 16))
        bmp = pack_nibbles(img)
        entries.append((cp, dict(box_w=bw, box_h=bh, ofs_x=ofs_x, ofs_y=ofs_y,
                                 adv_w=adv_w, bitmap_index=len(bitmap), bitmap=bmp)))
        bitmap += bmp

    # 按码点排序（稀疏表要求升序）
    entries.sort(key=lambda e: e[0])

    # ASCII 段与前 95 个必须是连续 0x20..0x7E
    ascii_entries = [e for e in entries if 0x20 <= e[0] <= 0x7E]
    cjk_entries   = [e for e in entries if e[0] > 0x7E]

    glyph_dsc = [dummy] + [e[1] for e in ascii_entries] + [e[1] for e in cjk_entries]

    cjk_cps = [e[0] for e in cjk_entries]
    range_start = min(cjk_cps)
    range_len   = max(cjk_cps) - range_start + 1
    uoffs = [cp - range_start for cp in cjk_cps]

    return dict(
        name=name, size=size, line_height=line_height, base_line=descent,
        font=font, glyph_dsc=glyph_dsc, bitmap=bytes(bitmap),
        cjk_start=range_start, cjk_len=range_len, uoffs=uoffs,
        n_ascii=len(ascii_entries), n_cjk=len(cjk_entries),
        cap_height=max(1, int(round(ascent * 0.72))),
        x_height=max(1, int(round(ascent * 0.52))),
    )


def emit_c(fonts, path_c, path_h):
    with io.open(path_c, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/*\n * Auto-generated by tools/gen_lvgl_font.py - DO NOT EDIT\n'
                ' * Source font: Noto Sans SC (OTF)\n'
                ' * Charset: ASCII 0x20-0x7E + UI Chinese copy\n */\n')
        f.write('#include "embersigh_fonts.h"\n\n')
        f.write('#if LVGL_VERSION_MAJOR >= 8\n')
        f.write('#include "lvgl.h"\n')
        f.write('#endif\n\n')

        for fi, ft in enumerate(fonts):
            tag = fi
            # 位图
            bmp = ft['bitmap']
            f.write(f'/* ---- {ft["name"]} : {ft["size"]}px, '
                    f'{len(bmp)} bytes bitmap ---- */\n')
            f.write(f'static const uint8_t glyph_bitmap_{tag}[] = {{\n')
            for i in range(0, len(bmp), 24):
                chunk = bmp[i:i+24]
                f.write('    ' + ', '.join(f'0x{b:02X}' for b in chunk) + ',\n')
            f.write('};\n\n')

            # unicode 偏移表
            if ft['uoffs']:
                f.write(f'static const uint16_t unicode_list_{tag}[] = {{\n')
                for i in range(0, len(ft['uoffs']), 16):
                    chunk = ft['uoffs'][i:i+16]
                    f.write('    ' + ', '.join(f'0x{v:04X}' for v in chunk) + ',\n')
                f.write('};\n\n')

            # cmap
            f.write(f'static const lv_font_fmt_txt_cmap_t cmaps_{tag}[] = {{\n')
            f.write('    {\n')
            f.write(f'        .range_start = 32, .range_length = 95, .glyph_id_start = 1,\n')
            f.write('        .unicode_list = NULL, .glyph_id_ofs_list = NULL, '
                    '.list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY\n')
            f.write('    },\n')
            f.write('    {\n')
            f.write(f'        .range_start = {ft["cjk_start"]}, '
                    f'.range_length = {ft["cjk_len"]}, '
                    f'.glyph_id_start = {1 + ft["n_ascii"]},\n')
            f.write(f'        .unicode_list = unicode_list_{tag}, .glyph_id_ofs_list = NULL, '
                    f'.list_length = {len(ft["uoffs"])}, '
                    '.type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY\n')
            f.write('    }\n};\n\n')

            # glyph_dsc
            f.write('static const lv_font_fmt_txt_glyph_dsc_t '
                    f'glyph_dsc_{tag}[] = {{\n')
            f.write('    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, '
                    '.ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,\n')
            for g in ft['glyph_dsc'][1:]:
                f.write(f'    {{.bitmap_index = {g["bitmap_index"]}, '
                        f'.adv_w = {g["adv_w"]}, .box_w = {g["box_w"]}, '
                        f'.box_h = {g["box_h"]}, .ofs_x = {g["ofs_x"]}, '
                        f'.ofs_y = {g["ofs_y"]}}},\n')
            f.write('};\n\n')

            # font_dsc
            f.write(f'static const lv_font_fmt_txt_dsc_t font_dsc_{tag} = {{\n')
            f.write(f'    .glyph_bitmap = glyph_bitmap_{tag},\n')
            f.write(f'    .glyph_dsc = glyph_dsc_{tag},\n')
            f.write(f'    .cmaps = cmaps_{tag},\n')
            f.write('    .kern_dsc = NULL,\n')
            f.write('    .kern_scale = 0,\n')
            f.write('    .cmap_num = 2,\n')
            f.write('    .bpp = 4,\n')
            f.write('    .kern_classes = 0,\n')
            f.write('    .bitmap_format = 0,\n')
            f.write('};\n\n')

            # 公开字体
            f.write(f'const lv_font_t {ft["name"]} = {{\n')
            f.write('    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,\n')
            f.write('    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,\n')
            f.write(f'    .line_height = {ft["line_height"]},\n')
            f.write(f'    .base_line = {ft["base_line"]},\n')
            f.write(f'    .cap_height = {ft["cap_height"]},\n')
            f.write(f'    .x_height = {ft["x_height"]},\n')
            f.write('    .subpx = LV_FONT_SUBPX_NONE,\n')
            f.write('    .underline_position = -1,\n')
            f.write('    .underline_thickness = 1,\n')
            f.write('    .static_bitmap = 1,\n')
            f.write(f'    .dsc = &font_dsc_{tag},\n')
            f.write('    .fallback = NULL,\n')
            f.write('    .user_data = NULL,\n')
            f.write('};\n\n')

    with io.open(path_h, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Auto-generated by tools/gen_lvgl_font.py - DO NOT EDIT */\n')
        f.write('#pragma once\n\n#include "lvgl.h"\n\n')
        f.write('#ifdef __cplusplus\nextern "C" {\n#endif\n\n')
        for ft in fonts:
            f.write(f'LV_FONT_DECLARE({ft["name"]});\n')
        f.write('\n#ifdef __cplusplus\n}\n#endif\n')


def main():
    fonts = []
    for name, size in SIZES:
        ft = build_font(name, size)
        print(f'{name}: {size}px  line_h={ft["line_height"]} base={ft["base_line"]} '
              f'glyphs={len(ft["glyph_dsc"])-1} bitmap={len(ft["bitmap"])}B '
              f'(ascii={ft["n_ascii"]} cjk={ft["n_cjk"]})')
        fonts.append(ft)

    emit_c(fonts,
           os.path.join(OUT_DIR, 'embersigh_fonts.c'),
           os.path.join(OUT_DIR, 'embersigh_fonts.h'))

    c_size = os.path.getsize(os.path.join(OUT_DIR, 'embersigh_fonts.c'))
    print(f'\n生成完成: embersigh_fonts.c ({c_size/1024:.1f} KB)')


if __name__ == '__main__':
    main()
